-- ============================================================================
-- LOKI Trading Platform — Supabase Data Vault schema
-- ============================================================================
-- HOW TO USE
--   1. Create a project at https://supabase.com (free tier is fine).
--   2. Open the SQL Editor in the Supabase dashboard, paste this file, RUN.
--   3. Get your project URL and the Service Role key:
--        Dashboard → Project Settings → API → "Project URL" + "service_role"
--   4. Add them as environment variables:
--        SUPABASE_URL=https://<project-ref>.supabase.co
--        SUPABASE_SERVICE_KEY=<service_role key>
--      (Locally: put them in a .env file that sits next to main.py.
--       On Vercel: Project → Settings → Environment Variables.)
--   5. Done. The engine logs trades/signals/equity/regimes/training reports
--      automatically. The web UI footer shows "DB SYNCED" when live.
--
-- SECURITY NOTE: the service_role key bypasses row-level security, which is
-- required for server-side inserts. Keep it server-side only (env / secrets);
-- never ship it to browsers.
-- ============================================================================

create table if not exists loki_trades (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  symbol            text not null,
  side              text,                    -- long | short
  qty               numeric,
  entry_price       numeric,
  exit_price        numeric,
  pnl               numeric,
  pnl_pct           numeric,
  exit_reason       text,                    -- stop | target | signal | time | end | manual
  mode              text,                    -- paper | live
  source            text,                    -- engine | manual | council
  equity_at_trade   numeric,
  opened_at         timestamptz,
  closed_at         timestamptz
);
create index if not exists idx_loki_trades_symbol on loki_trades (symbol, created_at desc);

create table if not exists loki_signals (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  symbol            text not null,
  action            text,                    -- BUY | SELL
  score             numeric,
  confidence        numeric,
  entry_price       numeric,
  stop_loss         numeric,
  take_profit       numeric,
  regime            text,                    -- STRONG_BULL | BULL | RANGING | BEAR | CRISIS
  timeframe         text
);
create index if not exists idx_loki_signals_symbol on loki_signals (symbol, created_at desc);

create table if not exists loki_equity_snapshots (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  equity            numeric,
  cash              numeric,
  open_positions    int,
  mode              text
);
create index if not exists idx_loki_equity_time on loki_equity_snapshots (created_at desc);

create table if not exists loki_regime_events (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  symbol            text not null,
  from_state        text,
  to_state          text,
  confidence        numeric
);
create index if not exists idx_loki_regime_symbol on loki_regime_events (symbol, created_at desc);

create table if not exists loki_training_reports (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  period            text,
  payload           jsonb
);

create table if not exists loki_events (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  kind              text not null,
  payload           jsonb
);
create index if not exists idx_loki_events_kind on loki_events (kind, created_at desc);

-- Server-private vault. No browser role can read or write global trading data.
-- This is not a multi-tenant user schema; add owner-scoped policies before any
-- direct browser/user access. Service secrets stay exclusively on the server.
do $$
declare table_name text;
begin
  foreach table_name in array array['loki_trades','loki_signals','loki_equity_snapshots',
                                    'loki_regime_events','loki_training_reports','loki_events']
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
    execute format('grant select, insert on table public.%I to service_role', table_name);
    execute format('grant usage, select on sequence public.%I to service_role', table_name || '_id_seq');
  end loop;
end $$;
